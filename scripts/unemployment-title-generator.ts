// ============================================
// 중복 검사
// ============================================
function checkDuplicates(): void {
  const titles = Object.values(UNEMPLOYMENT_TITLE_MAP);
  const duplicates = titles.filter((title, index) => titles.indexOf(title) !== index);

  if (duplicates.length > 0) {
    console.error('❌ 중복된 타이틀 발견:');
    duplicates.forEach(dup => console.error(`  - ${dup}`));
    process.exit(1);
  }

  console.log('✅ 중복 없음 (총', titles.length, '개)');
}

// ============================================
// 타이틀 생성
// ============================================
function generateTitle(keyword: string): string {
  const cleaned = keyword.replace(/^실업급여-/, '').replace(/\.md$/, '');

  if (UNEMPLOYMENT_TITLE_MAP[keyword] || UNEMPLOYMENT_TITLE_MAP[`실업급여-${cleaned}`]) {
    return UNEMPLOYMENT_TITLE_MAP[keyword] || UNEMPLOYMENT_TITLE_MAP[`실업급여-${cleaned}`];
  }

  console.warn(`⚠️  매핑 없음: ${keyword} (기본 패턴 사용)`);
  return `실업급여 ${cleaned}: 조건 및 방법`;
}

