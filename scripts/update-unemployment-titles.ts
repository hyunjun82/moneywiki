const wikiDir = path.join(process.cwd(), 'content', 'wiki');

let updated = 0;
let skipped = 0;

Object.entries(TITLE_MAP).forEach(([keyword, newTitle]) => {
  const filePath = path.join(wikiDir, `${keyword}.md`);

  if (!fs.existsSync(filePath)) {
    console.warn(`⚠️  파일 없음: ${keyword}.md`);
    skipped++;
    return;
  }

  const content = fs.readFileSync(filePath, 'utf-8');
  const lines = content.split('\n');

  // title 라인 찾기 (frontmatter 안에서)
  let titleLineIndex = -1;
  for (let i = 1; i < Math.min(lines.length, 20); i++) {
    if (lines[i].startsWith('title:')) {
      titleLineIndex = i;
      break;
    }
  }

  if (titleLineIndex === -1) {
    console.warn(`⚠️  title 없음: ${keyword}.md`);
    skipped++;
    return;
  }

  // 이미 업데이트된 경우 스킵 (따옴표 있으면)
  if (lines[titleLineIndex].includes('"') && lines[titleLineIndex].includes(':')) {
    console.log(`✓ 이미 완료: ${keyword}.md`);
    skipped++;
    return;
  }

  // 타이틀 교체
  lines[titleLineIndex] = `title: "${newTitle}"`;
  fs.writeFileSync(filePath, lines.join('\n'), 'utf-8');

  console.log(`✅ 업데이트: ${keyword}.md`);
  updated++;
});

console.log(`\n완료: ${updated}개 업데이트, ${skipped}개 스킵`);
