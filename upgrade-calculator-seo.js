// 이미 완벽한 파일은 스킵
const skip = ['연봉-실수령액-계산기.md'];

let updated = 0;
let skipped = 0;

const files = fs.readdirSync(dir).filter(f => f.includes('계산기') && f.endsWith('.md'));

files.forEach(filename => {
  if (skip.includes(filename)) {
    console.log(`SKIP: ${filename} (이미 완벽)`);
    skipped++;
    return;
  }

  const upgrade = upgrades[filename];
  if (!upgrade) {
    console.log(`NO UPGRADE DATA: ${filename}`);
    return;
  }

  const filePath = path.join(dir, filename);
  const raw = fs.readFileSync(filePath, 'utf8');
  const parsed = matter(raw);

  // 1. description 업그레이드
  parsed.data.description = upgrade.description;

  // 2. tool 필드 추가 (featureList)
  if (!parsed.data.tool) {
    parsed.data.tool = {
      featureList: upgrade.featureList,
    };
  } else if (!parsed.data.tool.featureList) {
    parsed.data.tool.featureList = upgrade.featureList;
  }

  // 3. summary 추가 (없는 경우)
  if (!parsed.data.summary && upgrade.addSummary) {
    parsed.data.summary = upgrade.addSummary;
  }

  // stringify back
  const output = matter.stringify(parsed.content, parsed.data);
  fs.writeFileSync(filePath, output, 'utf8');
  updated++;
  console.log(`UPDATED: ${filename} (desc: ${upgrade.description.length}자)`);
});

console.log(`\n완료: ${updated}개 업데이트, ${skipped}개 스킵`);
