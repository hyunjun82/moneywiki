      <P>ISA(개인종합자산관리계좌) 안에서 발생한 금융소득은 비과세 혜택을 받아 집계에서 제외돼요. 금융소득이 많다면 ISA나 연금저축 계좌를 활용하는 것도 하나의 방법이에요.</P>

