/** 화면과 같은 문장으로 FAQPage 구조화 데이터를 만든다 (홈 시안 helmet에 있던 것). */
export function faqJsonLd(items: GoldFaq[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map((f) => ({
      "@type": "Question",
      name: f.q,
      acceptedAnswer: { "@type": "Answer", text: f.a },
    })),
  };
}
